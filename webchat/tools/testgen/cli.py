        with pytest.raises(UploadTooLargeError):
            validate_attachment(kind="audio", byte_size=MAX_AUDIO_BYTES + 1, duration_ms=10_000)
        with pytest.raises(InvalidAttachmentError):
            validate_attachment(kind="audio", byte_size=1000, duration_ms=300_001)


