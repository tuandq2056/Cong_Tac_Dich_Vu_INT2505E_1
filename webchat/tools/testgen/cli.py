def generate_tests_for_service(service: str, target_dir: Path) -> Path:
    target_dir.mkdir(parents=True, exist_ok=True)
    out_file = target_dir / "test_generated_domain.py"

    if service == "identity":
        content = IDENTITY_TEST_TEMPLATE
    elif service == "social":
        content = SOCIAL_TEST_TEMPLATE
    elif service == "chat":
        content = CHAT_TEST_TEMPLATE
    else:
        raise ValueError(f"Unknown service: {service}")

    out_file.write_text(content.strip() + "\n", encoding="utf-8")
    return out_file


def main() -> int:
    parser = argparse.ArgumentParser(description="WebChat SOA Unit Test Generator")
    parser.add_argument(
        "--service",
        choices=["identity", "social", "chat", "all"],
        default="all",
        help="Target service to generate tests for (default: all)",
    )
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parent.parent.parent
    services = ["identity", "social", "chat"] if args.service == "all" else [args.service]

    print(f"Generating unit test suites for: {', '.join(services)}")
    generated_files = []

    for svc in services:
        target_dir = repo_root / "services" / svc / "tests"
        if not target_dir.parent.exists():
            print(f"Skipping {svc}: directory not found", file=sys.stderr)
            continue
        out_file = generate_tests_for_service(svc, target_dir)
        generated_files.append(out_file)
        print(f"  [+] Generated: {out_file.relative_to(repo_root)}")

    print(f"SUCCESS: Generated {len(generated_files)} test suite(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
