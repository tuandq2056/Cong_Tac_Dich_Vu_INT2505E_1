    def test_read_state_monotonicity(self) -> None:
        # Read-state only moves forward (ADR 0006)
        # Tab 1: advances to 45
        s1 = clamp_read_state(current_last_read_seq=0, through_seq=45, latest_seq=50)
        assert s1 == 45
        # Tab 2: stale update with 40 -> remains 45
